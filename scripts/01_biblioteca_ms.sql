    EXECUTE IMMEDIATE 'DROP TABLE LIBRO CASCADE CONSTRAINTS PURGE';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -942 THEN RAISE; END IF;
END;
/

CREATE TABLE LIBRO (
    ID               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    TITULO           VARCHAR2(200) NOT NULL,
    AUTOR            VARCHAR2(150) NOT NULL,
    ANIO_PUBLICACION NUMBER(4)     NOT NULL,
    GENERO           VARCHAR2(80)  NOT NULL,
    CONSTRAINT PK_LIBRO PRIMARY KEY (ID),
    CONSTRAINT CK_LIBRO_ANIO CHECK (ANIO_PUBLICACION BETWEEN 1000 AND 2100)
);

